test('local PDF lifecycle validates MIME, extension, size, bytes; refresh requires SHA256-matched reselection', async () => {
    const { service, local, tab } = session();
    const file = new File(['%PDF-1.4\nfictional evidence'], 'perangkat.pdf', { type: 'application/pdf' });
    const meta = await service.registerLocalFile('attempt-1', file);
    assert.ok(meta.sha256);
    assert.ok(service.getFileUrl(meta.id));
    const content = fixtureContent('participant_report');
    content.mainDocument = meta;
    const d = service.saveDraft('attempt-1', content, 0);
    const v = service.submitPackage('attempt-1', d.revision, true);
    assert.ok(service.getFileUrl(meta.id));
    const refreshed = createMockService({ localStorage: local, sessionStorage: tab });
    assert.equal(refreshed.fileAvailable(meta.id), false);
    assert.equal(refreshed.getFileUrl(meta.id), null);
    await assert.rejects(() => refreshed.restoreLocalFile(v.id, meta.id, new File(['%PDF-1.4\ndifferent evidence'], 'perangkat.pdf', { type: 'application/pdf' })), /cocok|berbeda/i);
    await refreshed.restoreLocalFile(v.id, meta.id, file);
    assert.equal(refreshed.fileAvailable(meta.id), true);
    assert.deepEqual(refreshed.getEvidence(v.id).version, v);
    refreshed.switchAccount('pengelola-1');
    await assert.rejects(() => refreshed.restoreLocalFile(v.id, meta.id, file), /pemilik/);
    const registry = createFileRegistry();
    for (const bad of [new File(['<script>bad</script>'], 'bad.pdf', { type: 'application/pdf' }), new File(['%PDF-1.4'], 'bad.html', { type: 'application/pdf' }), new File(['%PDF-1.4'], 'bad.pdf', { type: 'text/html' }), new File([new Uint8Array(MAX_FILE_SIZE + 1)], 'big.pdf', { type: 'application/pdf' })])
        await assert.rejects(() => registry.register(bad));
    registry.clear();
});
test('async file registration and restore cannot commit after actor switch or reset', async () => {
    const registry = createFileRegistry();
    let release!: () => void;
    const hold = () => new Promise<void>(resolve => { release = resolve; });
    let delayed = false;
    const slow: FileRuntime = { ...registry, async register(file) { await hold(); return registry.register(file); }, async restore(meta, file) { if (delayed)
            await hold(); return registry.restore(meta, file); } };
    const local = storage(), tab = storage(), service = createMockService({ localStorage: local, sessionStorage: tab, files: slow });
    service.login('peserta@demo.invalid', DEMO_PASSWORD);
    const file = new File(['%PDF-1.4\nhello'], 'sample.pdf', { type: 'application/pdf' });
    const pending = service.registerLocalFile('attempt-1', file);
    service.switchAccount('pengelola-1');
    release();
    await assert.rejects(() => pending, /berubah/);
    service.switchAccount('peserta-1');
    const pending2 = service.registerLocalFile('attempt-1', file);
    service.reset();
    release();
    await assert.rejects(() => pending2, /berubah/);
    service.login('peserta@demo.invalid', DEMO_PASSWORD);
    const pending3 = service.registerLocalFile('attempt-1', file);
    release();
    const meta = await pending3;
    const content = fixtureContent('participant_report');
    content.mainDocument = meta;
    const d = service.saveDraft('attempt-1', content, 0), v = service.submitPackage('attempt-1', d.revision, true);
    registry.clear();
    delayed = true;
    const restoring = service.restoreLocalFile(v.id, meta.id, file);
    service.switchAccount('pengelola-1');
    release();
    await assert.rejects(() => restoring, /berubah/);
    assert.equal(service.fileAvailable(meta.id), false);
});
test('revision archives prior moderation/publication and does not carry old workflow into a new package', () => {
    const seed = createSeed();
    const old = seed.data.attempts.find(a => a.id === 'attempt-5')!;
    old.publication = { status: 'published', version: 1, feedback: 'Feedback contoh versi lama' };
    const { service } = session(seed);
    service.switchAccount('pengelola-1');
    const version = service.listSubmittedPackages().find(r => r.attemptId === old.id)!;
    service.reviewPackage(version.id, { outcome: 'needs_correction', checks: { ...checks, perangkat: false }, issues: { perangkat: 'Perangkat contoh perlu perbaikan.' } });
    const state = service.getSnapshot(), attempt = state.data.attempts.find(a => a.id === old.id)!, event = state.data.activities.at(-1)!;
    assert.equal(attempt.moderation, 'none');
    assert.equal(attempt.publication.status, 'withdrawn');
    assert.equal(attempt.publication.feedback, old.publication.feedback);
    assert.equal(event.previousState?.moderation, 'open');
    assert.equal(event.previousState?.publication.status, 'published');
    assert.equal(event.previousState?.assignmentIds.length, 2);
    assert.equal(state.data.assignments.filter(a => a.attemptId === old.id && a.assessmentStatus === 'final' && !a.active).length, 2);
    assert.ok(isSnapshot(state));
});

